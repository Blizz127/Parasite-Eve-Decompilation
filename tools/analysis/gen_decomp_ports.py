def targets(only):
    names = []
    for fn in sorted(os.listdir(DECOMP_DIR)):
        if not fn.endswith("_port.c"):
            continue
        names.append(fn[:-len("_port.c")])
    if only:
        names = [n for n in names if n in only]
    return names


def generate_one(name, src_text, meta, defined):
    fn = find_function(src_text, name)
    is_ptr = fn is not None and any(p[2] for p in parse_params(fn[1]))
    if is_ptr:
        return generate_ptr(name, src_text, meta, defined)
    return generate_leaf(name, src_text, meta, defined)


def existing_boundary_callees(text):
    return set(
        re.findall(
            r"#define\s+(func_[0-9A-Fa-f]+)\(\.\.\.\)\s+PE_D_COMP_BOUNDARY", text
        )
    )


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify, write nothing")
    ap.add_argument("--only", action="append", default=[], help="one leaf name")
    ap.add_argument(
        "--allow-orphans",
        action="store_true",
        help="with --check, tolerate TUs that have no src/ leaf (the checked-in"
             " orphan manifest is the authority for those)",
    )
    ap.add_argument(
        "--update-orphans",
        action="store_true",
        help="rewrite tools/analysis/decomp_port_orphans.txt from the current tree",
    )
    args = ap.parse_args(argv)

    entries = parse_subsegments(CONFIG)
    meta = build_meta(entries)
    defined = collect_defined_symbols()

    names = targets(set(args.only))
    if args.only:
        missing = set(args.only) - set(names)
        if missing:
            raise SystemExit("unknown leaf(s): %s" % ", ".join(sorted(missing)))

    orphans = []
    changed = []
    stale = []
    failed = []
    for name in names:
        srcp = os.path.join(SRC_DIR, name + ".c")
        dstp = os.path.join(DECOMP_DIR, name + "_port.c")
        if not os.path.exists(srcp):
            orphans.append(name)
            continue
        if name not in meta:
            failed.append((name, "no config subsegment metadata"))
            continue
        src_text = open(srcp, encoding="utf-8").read()
        existing = open(dstp, encoding="utf-8").read()
        generated = generate_one(name, src_text, meta[name], defined)
        if generated == existing:
            continue
        # A mismatch is "stale" when the existing TU was produced with a
        # different implemented-symbol view: it replaces a callee prototype
        # with a shim marker but emits no boundary define, so the call binds
        # to a callee the current tree now implements.  Regeneration differs
        # only in that binding.
        markers = set(
            re.findall(
                r"/\* shimmed by pe_guest_decomp\.h: (func_[0-9A-Fa-f]+) \*/",
                existing,
            )
        )
        boundary_defs = existing_boundary_callees(existing)
        if markers - boundary_defs:
            stale.append((name, sorted(markers - boundary_defs)))
            if not args.check:
                open(dstp, "w", encoding="utf-8").write(generated)
            continue
        used_callees = set(CALL_RE.findall(src_text)) - {name}
        forced = defined - used_callees
        if generate_one(name, src_text, meta[name], forced) == existing:
            boundary_now = sorted(used_callees & defined)
            stale.append((name, boundary_now))
            if not args.check:
                open(dstp, "w", encoding="utf-8").write(generated)
            continue
        changed.append(name)
        if not args.check:
            open(dstp, "w", encoding="utf-8").write(generated)

    print("targets: %d" % len(names))
    print("orphans (no src/ leaf, cannot regenerate): %d" % len(orphans))
    for n in orphans:
        print("  orphan %s" % n)
    print("stale boundaries (callee is now implemented): %d" % len(stale))
    for n, cals in stale:
        print("  stale %s (boundary: %s)" % (n, ", ".join(cals)))
    print("mismatched (regeneration differs): %d" % len(changed))
    for n in changed:
        print("  mismatch %s" % n)
    if failed:
        print("errors: %d" % len(failed))
        for n, why in failed:
            print("  error %s: %s" % (n, why))
    if args.update_orphans:
        with open(ORPHANS_FILE, "w", encoding="utf-8") as fh:
            fh.write("# pc_port/game/decomp TUs with no matching src/ leaf.\n")
            fh.write("# Machine-checked by tools/analysis/gen_decomp_ports.py"
                     " and the decomp-port regression test.\n")
            for n in orphans:
                fh.write(n + "\n")
        print("wrote %s (%d entries)" % (ORPHANS_FILE, len(orphans)))

    if args.check:
        bad = len(changed) + len(stale) + len(failed)
        if args.allow_orphans:
            expected = read_orphan_manifest()
            new = sorted(set(orphans) - expected)
            fixed = sorted(expected - set(orphans))
            if new:
                print("new orphans (not in %s): %d" % (ORPHANS_FILE, len(new)))
                for n in new:
                    print("  new-orphan %s" % n)
                bad += len(new)
            if fixed:
                print("manifest entries that now have a src/ leaf: %d" % len(fixed))
                for n in fixed:
                    print("  fixed %s" % n)
                bad += len(fixed)
        else:
            bad += len(orphans)
        print("check: %s" % ("FAIL" if bad else "OK"))
        return 1 if bad else 0
    print("wrote %d file(s)" % (len(names) - len(orphans) - len(failed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
